"""Regenerate README images and the BOM from the saved KiCad project.

Requires Python 3.10+, KiCad 10+ and standard
KiCad 3D models. No pip packages are needed. Source design files are never saved.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import sys
import tempfile
import time

from check_bom import audit
from kicad_helpers import ROOT, cli_path, model_directory, run, write_if_changed


def source_files(config):
    paths = [*ROOT.glob("*.kicad_sch"), ROOT / "OpenBridge.kicad_pcb", ROOT / "OpenBridge.kicad_pro", ROOT / "OpenBridge.kicad_sym", ROOT / "fp-lib-table", ROOT / "sym-lib-table", config]
    paths += list((ROOT / "OpenBridge.pretty").glob("*.kicad_mod"))
    paths += list((ROOT / "OpenBridge.3dshapes").glob("*"))
    return sorted(set(p for p in paths if p.is_file()))


def fingerprint(files):
    digest = hashlib.sha256()
    for file in files:
        digest.update(file.name.encode())
        digest.update(file.read_bytes())
    return digest.hexdigest()


def clean_svg(file):
    # KiCad includes export time in a generator comment; omit it for clean diffs.
    text = file.read_text(encoding="utf-8")
    text = re.sub(r"<!--\s*Creator:.*?-->", "<!-- Generated by KiCad; run scripts/update_previews.py -->", text, flags=re.S)
    return re.sub(r"<title>.*?</title>", "<title>OpenBridge — generated KiCad preview</title>", text, flags=re.S)


def pcb_preview(file):
    text = clean_svg(file)
    # Keep KiCad's native orientation and viewport, adding only the dark backdrop.
    match = re.search(r'<svg\b.*?>', text, re.S)
    header = match[0]
    bounds = re.search(r'viewBox="([^"]+)"', header)[1].split()
    x, y, width, height = map(float, bounds)
    if x or y:
        raise ValueError("Unexpected PCB SVG origin")
    body = text[match.end():text.rfind('</svg>')].replace('#FFFFFF', '#151C26')
    return text[:match.start()] + header + f'\n<rect width="{width}" height="{height}" fill="#151C26"/>\n' + body + '\n</svg>\n'


def validate_render_outline(cli, board, env=None):
    """Use KiCad's geometry checks: endpoint connectivity misses self-intersections."""
    report = Path(board).with_suffix(".outline-drc.json")
    run([cli, "pcb", "drc", "--format", "json", "--output", report, board], env=env)
    findings = json.loads(report.read_text(encoding="utf-8"))["violations"]
    failures = [item["description"] for item in findings if item["type"] == "invalid_outline"]
    if failures:
        raise ValueError("KiCad rejected the render outline: " + "; ".join(sorted(set(failures))))


def stackup_color_args(cli, env=None):
    # KiCad 10.0.0 defaults to true; explicitly passing its advertised boolean
    # argument crashes with bad_any_cast. Newer 10.0 releases use an opt-in flag.
    help_text = run([cli, "pcb", "render", "--help"], env=env)
    flag = "--use-board-stackup-colors"
    if flag not in help_text:
        raise RuntimeError("This KiCad renderer cannot apply the configured board color")
    return [] if flag + " VAR" in help_text else [flag]


def generate(args):
    cli = cli_path(args.kicad_cli)
    config_file = Path(args.config).resolve()
    config = json.loads(config_file.read_text(encoding="utf-8"))
    color = config["board_color"]
    if not re.fullmatch(r"(?:Black|Green|Red|Blue|Purple|Yellow|White|#[0-9a-fA-F]{6})", color):
        raise ValueError("board_color must be a KiCad color name or #RRGGBB")
    files = source_files(config_file)
    before = fingerprint(files)
    destination = ROOT / "docs/images"
    env = os.environ.copy()
    env["KICAD10_3DMODEL_DIR"] = model_directory(cli)
    env["KIPRJMOD"] = str(ROOT)
    with tempfile.TemporaryDirectory(prefix="openbridge-preview-") as scratch:
        work = Path(scratch)
        cfg = work / "config"
        cfg.mkdir()
        # Isolate rendering from the user's hidden-model flags, colors and caches.
        viewer = {"meta": {"version": 4}, "use_stackup_colors": True, "render": {
            "show_footprints_normal": True, "show_footprints_insert": True,
            "show_footprints_virtual": True, "show_footprints_not_in_posfile": True,
            "show_footprints_dnp": False, "show_board_body": True,
            "show_silkscreen_top": True, "show_silkscreen_bottom": True,
            "show_soldermask_top": True, "show_soldermask_bottom": True,
            "show_copper_top": True, "show_copper_bottom": True,
            "show_zones": True, "show_axis": False,
            "show_comments": False, "show_drawings": False,
            "raytrace_reflections": True, "raytrace_shadows": True,
            "raytrace_anti_aliasing": True, "raytrace_post_processing": True}}
        (cfg / "3d_viewer.json").write_text(json.dumps(viewer))
        env["KICAD_CONFIG_HOME"] = str(cfg)
        render_board = work / "OpenBridge-render.kicad_pcb"
        shutil.copy2(ROOT / "OpenBridge.kicad_pcb", render_board)
        shutil.copy2(ROOT / "OpenBridge.kicad_pro", render_board.with_suffix(".kicad_pro"))
        run([sys.executable, ROOT / "scripts/prepare_render.py", render_board, config_file], env=env)
        validate_render_outline(cli, render_board, env)
        print(f"Rendering main board in {color}...")
        run([cli, "pcb", "render", "--output", work / "assembly.png", "--width", config["width"], "--height", config["height"],
             "--rotate", ",".join(map(str, config["rotation"])), "--zoom", config["zoom"], "--quality", config["quality"],
             "--background", "transparent", *stackup_color_args(cli, env), render_board], env=env)
        run([cli, "sch", "export", "svg", "--output", work / "schematics", "--exclude-drawing-sheet", ROOT / "OpenBridge.kicad_sch"], env=env)
        # Plot bottom copper first so blue B.Cu sits beneath red F.Cu.
        # The 2D view shows the full panel used for fabrication.
        run([cli, "pcb", "export", "svg", "--output", work / "pcb.svg", "--mode-single", "--layers", "B.Cu,F.Cu,F.SilkS,Edge.Cuts",
             "--page-size-mode", "2", "--exclude-drawing-sheet", ROOT / "OpenBridge.kicad_pcb"], env=env)
        schematics = list((work / "schematics").glob("*.svg"))
        main = next((p for p in schematics if p.name == "OpenBridge.svg"), None)
        hardware = next((p for p in schematics if "hardware" in p.name.lower()), None)
        if main is None or hardware is None:
            raise RuntimeError(f"Expected circuit and Hardware schematic exports; found {schematics}")
        audit(work / "bom.csv")
        if fingerprint(files) != before:
            raise RuntimeError("Source changed during rendering; run again to publish a consistent set")
        write_if_changed(destination / "assembly.png", (work / "assembly.png").read_bytes())
        for source, name in [(main, "schematic.svg"), (hardware, "hardware.svg")]:
            write_if_changed(destination / name, clean_svg(source))
        write_if_changed(destination / "pcb.svg", pcb_preview(work / "pcb.svg"))
        write_if_changed(ROOT / "docs/bom.csv", (work / "bom.csv").read_bytes())
    print("Updated docs/images and docs/bom.csv; source design files unchanged.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=str(ROOT / "scripts/render-config.json"))
    parser.add_argument("--kicad-cli")
    parser.add_argument("--watch", action="store_true", help="Regenerate after saved design/config changes; Ctrl+C to stop")
    args = parser.parse_args()
    generate(args)
    if args.watch:
        config = Path(args.config).resolve()
        last = fingerprint(source_files(config))
        print("Watching saved design and render configuration files...")
        try:
            while True:
                time.sleep(2)
                current = fingerprint(source_files(config))
                if current != last:
                    time.sleep(1)  # Debounce multi-file KiCad saves.
                    try:
                        generate(args)
                        last = fingerprint(source_files(config))
                    except (RuntimeError, ValueError, OSError) as error:
                        print(f"Preview update failed: {error}", file=sys.stderr)
                        last = current
        except KeyboardInterrupt:
            print("Stopped watching.")


if __name__ == "__main__":
    main()
